// Export ONLY translations matched to cached official articles. Never export the key or user settings.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
function exportNews(db){
 const entries=[];
 for(const a of (db.items||[]).slice(0,8)){
  const t=db.translations?.[a.hash];
  if(!/^\d+$/.test(a.id)||typeof a.text!=='string'||crypto.createHash('sha256').update(a.text).digest('hex')!==a.hash||typeof t?.text!=='string'||!t.text.trim()||t.text.length>180000||/AIza[\w-]{30,}/.test(t.text))continue;
  let u;try{u=new URL(a.url);}catch{continue;}
  if(u.protocol!=='https:'||!['store.steampowered.com','steamcommunity.com','steamstore-a.akamaihd.net'].includes(u.hostname)||u.username||u.password)continue;
  entries.push({id:a.id,hash:a.hash,text:t.text,at:Number(t.at)||0});
 }
 return {schema:1,language:'ko',entries};
}
module.exports={exportNews};
if(require.main===module){
 const [input,output,bundle]=process.argv.slice(2);if(!input||!output||!bundle)throw Error('Usage: node export-news.cjs game-news.json news/ko.json source/app/news-ko.js');
 const data=exportNews(JSON.parse(fs.readFileSync(input,'utf8')));if(!data.entries.length)throw Error('No verified translations');
 const json=JSON.stringify(data,null,2)+'\n';fs.mkdirSync(path.dirname(output),{recursive:true});fs.writeFileSync(output,json);fs.writeFileSync(bundle,'// Public official-news translations only. Generated by export-news.cjs.\nmodule.exports='+json.trim()+';\n');console.log(JSON.stringify({articles:data.entries.length,bytes:Buffer.byteLength(json)}));
}
